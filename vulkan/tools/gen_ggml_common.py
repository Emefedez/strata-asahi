#!/usr/bin/env python3
"""vulkan/tools/gen_ggml_common.py - write vulkan/kernels/ggml_common.slang: the lookup tables of
third_party/ggml/ggml-common.h (the i-quant grids, sign tables and codebooks) as Slang constant arrays, the role
ggml-common.h plays for the Metal kernels (prepended with GGML_COMMON_IMPL_METAL). Run after updating ggml:

    python3 vulkan/tools/gen_ggml_common.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "third_party/ggml/ggml-common.h"
OUT = ROOT / "vulkan/kernels/ggml_common.slang"
WANT = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid", "kvalues_iq4nl"]
TYPES = {"uint8_t": "uint", "int8_t": "int", "uint32_t": "uint", "uint64_t": "uint64_t"}

text = SRC.read_text()
out = [
    "// vulkan/kernels/ggml_common.slang - GENERATED by vulkan/tools/gen_ggml_common.py from",
    "// third_party/ggml/ggml-common.h: do not edit. The tables the Metal kernels read from ggml-common.h.",
    "// Bytes and int8 are widened to 32-bit words (no 8-bit constant arrays needed); the values are the same.",
    "",
]
for name in WANT:
    m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*" + name + r",\s*(\w+)\)(.*?)GGML_TABLE_END\(\)", text, re.S)
    if not m:
        sys.exit(f"{name} not found in {SRC}")
    ctype, size, body = m.group(1), m.group(2), m.group(3)
    vals = [v for v in re.split(r"[,\s]+", re.sub(r"//.*", "", body)) if v]
    if size.isdigit() and len(vals) != int(size):
        sys.exit(f"{name}: {len(vals)} values, expected {size}")
    if ctype == "uint64_t":
        vals = [v.rstrip("uUlL") + "ULL" for v in vals]
    else:
        vals = [v.rstrip("uUlL") for v in vals]
    out.append(f"// {ctype} {name}[{len(vals)}]")
    out.append(f"static const {TYPES[ctype]} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(vals[i:i + 8]) + ",")
    out.append("};")
    out.append("")
OUT.write_text("\n".join(out))
print(f"wrote {OUT} ({len(WANT)} tables)")
